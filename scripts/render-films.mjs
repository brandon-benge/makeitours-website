// makeitours-app#60: the BYOI films on Getting Started, from content/films.json.
// `--check` fails when getting-started.html is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { film } from './render-hosted.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const films = JSON.parse(readFileSync(join(root, 'content', 'films.json'), 'utf8'));
const target = join(root, 'getting-started.html');
const page = readFileSync(target, 'utf8');
const start = '<!-- films:start (generated by scripts/render-films.mjs) -->';
const end = '<!-- films:end -->';
const body = `${start}
  <h2 id="byoi-films">Bring Your Own Infra, step by step</h2>
  <p>These short films show the setup on a demo account. They have no sound; the captions are in the picture.</p>
${film(films.byoiOverview, 'Film: Bring Your Own Infra overview', 'overview:byoi')}  <div class="film-grid" data-film-slot="byoi-setup">
${films.byoiSetup.map(s => film(s.film, `Film: ${s.title}`)).join('')}  </div>
  ${end}`;
const before = page.indexOf(start), after = page.indexOf(end);
if (before < 0 || after < 0) throw new Error('getting-started.html is missing the films markers');
const html = page.slice(0, before) + body + page.slice(after + end.length);
if (process.argv.includes('--check')) {
  if (html !== page) { console.error('getting-started.html is out of date: run node scripts/render-films.mjs'); process.exit(1); }
} else writeFileSync(target, html);
